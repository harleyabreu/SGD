BEGIN;

CREATE TABLE IF NOT EXISTS usuarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome TEXT NOT NULL,
    login TEXT NOT NULL UNIQUE,
    email TEXT NOT NULL UNIQUE,
    telefone TEXT,
    senha_hash TEXT NOT NULL,
    perfil TEXT NOT NULL,
    status TEXT NOT NULL,
    diretoria_sigla TEXT,
    diretoria_nome TEXT,
    gerencia_sigla TEXT,
    gerencia_nome TEXT,
    divisao_nome TEXT,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    atualizado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    ultimo_acesso TIMESTAMPTZ
);

CREATE TABLE IF NOT EXISTS clientes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome TEXT NOT NULL,
    sigla TEXT NOT NULL UNIQUE,
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    atualizado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS sistemas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome TEXT NOT NULL,
    cliente_id BIGINT REFERENCES clientes(id),
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    atualizado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (cliente_id, nome)
);

CREATE TABLE IF NOT EXISTS tipos_demanda (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome TEXT NOT NULL UNIQUE,
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    atualizado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS demandas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo TEXT NOT NULL,
    descricao TEXT NOT NULL,
    cliente_id BIGINT NOT NULL REFERENCES clientes(id),
    sistema_id BIGINT REFERENCES sistemas(id),
    tipo_demanda_id BIGINT NOT NULL REFERENCES tipos_demanda(id),
    responsavel_id BIGINT NOT NULL REFERENCES usuarios(id),
    criticidade TEXT,
    prioridade_atendimento TEXT,
    prioridade TEXT NOT NULL,
    prazo TEXT NOT NULL,
    observacao TEXT NOT NULL DEFAULT '',
    status TEXT NOT NULL,
    data_abertura TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    data_conclusao TIMESTAMPTZ,
    usuario_criacao_id BIGINT REFERENCES usuarios(id),
    usuario_conclusao_id BIGINT REFERENCES usuarios(id),
    data_reabertura TIMESTAMPTZ,
    usuario_reabertura_id BIGINT REFERENCES usuarios(id),
    prazo_dias_uteis INTEGER CHECK (prazo_dias_uteis IS NULL OR prazo_dias_uteis >= 0),
    prazo_manual BOOLEAN NOT NULL DEFAULT FALSE,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    atualizado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS comentarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    demanda_id BIGINT NOT NULL REFERENCES demandas(id),
    texto TEXT NOT NULL,
    usuario_id BIGINT REFERENCES usuarios(id),
    usuario_nome TEXT NOT NULL,
    data TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS arquivos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    demanda_id BIGINT NOT NULL REFERENCES demandas(id),
    nome TEXT NOT NULL,
    tamanho BIGINT NOT NULL CHECK (tamanho >= 0),
    data TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    usuario_id BIGINT REFERENCES usuarios(id),
    usuario_nome TEXT NOT NULL,
    url TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS periodos_pendencia (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    demanda_id BIGINT NOT NULL REFERENCES demandas(id),
    inicio TIMESTAMPTZ NOT NULL,
    fim TIMESTAMPTZ,
    motivo TEXT NOT NULL,
    CHECK (fim IS NULL OR fim >= inicio)
);

CREATE TABLE IF NOT EXISTS historico (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    demanda_id BIGINT NOT NULL REFERENCES demandas(id),
    tipo TEXT NOT NULL,
    titulo TEXT NOT NULL,
    descricao TEXT NOT NULL,
    data TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    usuario_id BIGINT REFERENCES usuarios(id),
    usuario_nome TEXT NOT NULL,
    referencia_id BIGINT,
    valor_anterior TEXT,
    valor_novo TEXT,
    motivo TEXT
);

CREATE INDEX IF NOT EXISTS idx_demandas_status
    ON demandas(status);

CREATE INDEX IF NOT EXISTS idx_demandas_responsavel
    ON demandas(responsavel_id);

CREATE INDEX IF NOT EXISTS idx_demandas_cliente
    ON demandas(cliente_id);

CREATE INDEX IF NOT EXISTS idx_demandas_prazo
    ON demandas(prazo);

CREATE INDEX IF NOT EXISTS idx_comentarios_demanda
    ON comentarios(demanda_id);

CREATE INDEX IF NOT EXISTS idx_arquivos_demanda
    ON arquivos(demanda_id);

CREATE INDEX IF NOT EXISTS idx_pendencias_demanda
    ON periodos_pendencia(demanda_id);

CREATE INDEX IF NOT EXISTS idx_historico_demanda
    ON historico(demanda_id, data);

COMMIT;